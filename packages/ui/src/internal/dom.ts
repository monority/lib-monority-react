export function canUseDOM() {
  return typeof window !== 'undefined' && typeof document !== 'undefined'
}

export const focusableSelector = [
  'a[href]',
  'button:not([disabled])',
  'textarea:not([disabled])',
  'input:not([disabled])',
  'select:not([disabled])',
  '[tabindex]:not([tabindex="-1"])',
].join(',')
